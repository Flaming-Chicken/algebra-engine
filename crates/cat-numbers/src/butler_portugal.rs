//! 1-WL + Butler-Portugal tensor index canonicalizer and Garnir Young projectors.
//!
//! Provides zero-allocation canonicalization of tensor monomials with permutation symmetries
//! and cyclicity identities (e.g. Riemann curvature tensor R_{abcd}).

use smallvec::SmallVec;

/// Symmetries for a tensor slot configuration.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TensorSymmetry {
    /// Generators of the index permutation automorphism group: (permutation, sign).
    /// For example, for Riemann R_{abcd}:
    /// - (1, 0, 2, 3) -> sign -1 (antisymmetric in first pair)
    /// - (0, 1, 3, 2) -> sign -1 (antisymmetric in second pair)
    /// - (2, 3, 0, 1) -> sign +1 (pair interchange symmetry)
    pub generators: Vec<([u8; 4], i8)>,
}

impl TensorSymmetry {
    /// Riemann curvature tensor R_{abcd} symmetries.
    pub fn riemann() -> Self {
        Self {
            generators: vec![
                ([1, 0, 2, 3], -1), // R_{bacd} = -R_{abcd}
                ([0, 1, 3, 2], -1), // R_{abdc} = -R_{abcd}
                ([2, 3, 0, 1], 1),  // R_{cdab} = +R_{abcd}
            ],
        }
    }
}

/// Butler-Portugal canonicalization result.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CanonicalTensorResult {
    /// Canonical index configuration.
    pub indices: [u8; 4],
    /// Overall sign (-1, 0, or +1). 0 indicates tensor vanishes identically under symmetry!
    pub sign: i8,
}

/// Butler-Portugal double coset index canonicalizer.
pub struct ButlerPortugal;

impl ButlerPortugal {
    /// Canonicalize 4-index tensor under symmetry generators (e.g. Riemann tensor).
    ///
    /// Explores group orbit generated by symmetry generators to find lexicographically
    /// minimal index permutation with overall sign.
    pub fn canonicalize_4(indices: [u8; 4], sym: &TensorSymmetry) -> CanonicalTensorResult {
        let mut min_indices = indices;
        let mut net_sign = 1i8;

        // BFS / DFS over orbit generated by symmetry generators
        let mut visited: SmallVec<[([u8; 4], i8); 16]> = SmallVec::new();
        let mut queue: SmallVec<[([u8; 4], i8); 8]> = SmallVec::new();

        visited.push((indices, 1));
        queue.push((indices, 1));

        while let Some((curr, sign)) = queue.pop() {
            if curr < min_indices {
                min_indices = curr;
                net_sign = sign;
            }

            for (g, gen_sign) in &sym.generators {
                let next = [
                    curr[g[0] as usize],
                    curr[g[1] as usize],
                    curr[g[2] as usize],
                    curr[g[3] as usize],
                ];
                let next_sign = sign * gen_sign;

                // Check for antisymmetry annihilation: if next == curr but next_sign == -sign, tensor vanishes!
                if next == curr && next_sign == -sign {
                    return CanonicalTensorResult {
                        indices: [0; 4],
                        sign: 0,
                    };
                }

                if !visited.iter().any(|(v, _)| *v == next) {
                    visited.push((next, next_sign));
                    queue.push((next, next_sign));
                }
            }
        }

        CanonicalTensorResult {
            indices: min_indices,
            sign: net_sign,
        }
    }

    /// Garnir Young projector for First Bianchi Identity:
    /// For Riemann curvature tensor, `R_{a[bcd]} = R_{abcd} + R_{acdb} + R_{adbc} = 0`.
    /// Reduces non-canonical cyclic triad R_{adbc} -> (-R_{abcd}, -R_{acdb}).
    pub fn garnir_bianchi_project(
        indices: [u8; 4],
        sym: &TensorSymmetry,
    ) -> SmallVec<[([u8; 4], i8); 2]> {
        let canon = Self::canonicalize_4(indices, sym);
        if canon.sign == 0 {
            return SmallVec::new();
        }
        let [a, b, c, d] = canon.indices;
        // In the standard Young tableau of shape (2,2):
        // | a | c |
        // | b | d |
        // with standard ordering: a < b < d and a < c < d and b < c.
        // If b > c, the tableau is non-standard and Garnir projection rewrites:
        // R_{a d b c} = -R_{a b c d} - R_{a c d b}
        if b > c {
            let t1 = Self::canonicalize_4([a, b, c, d], sym);
            let t2 = Self::canonicalize_4([a, c, d, b], sym);
            smallvec::smallvec![
                (t1.indices, -t1.sign * canon.sign),
                (t2.indices, -t2.sign * canon.sign),
            ]
        } else {
            smallvec::smallvec![(canon.indices, canon.sign)]
        }
    }
}
